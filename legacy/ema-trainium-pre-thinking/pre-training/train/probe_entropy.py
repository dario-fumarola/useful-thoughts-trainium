def score(x, anchors, Z, lens=None):
    """per-row CE over the spliced buffer, plus the entropy of the prediction at the target rows [N*nc]"""
    buf, pos, m, tgt = geo.score_buffer(x, anchors, Z, lens)
    with torch.no_grad():
        h = smodel.model(input_ids=torch.from_numpy(buf[None]), position_ids=torch.from_numpy(pos[None]),
                         attention_mask=torch.from_numpy(m[None, None]), use_cache=False)[0]
        lg = smodel.lm_head(h[0])
        lp = torch.log_softmax(lg.float(), -1)
        ce = -lp.gather(1, torch.from_numpy(tgt)[:, None])[:, 0].numpy()
        lpt = lp[torch.from_numpy(trows)]
        Ht = (-(lpt.exp() * lpt).sum(-1)).numpy()
    return ce, Ht


def decide_entropy(H0, Ht_row, ch, e_margin):
    """label-free: walk the checks; keep at the first prefix whose entropy on the next token fell by >= e_margin
    from the clean entropy H0; stop (discard) when entropy stops falling; discard at the budget."""
    prev = H0
    for c in range(len(Ht_row)):
        if H0 - Ht_row[c] >= e_margin:
            return ch * (c + 1)
        if Ht_row[c] >= prev:
            return 0
        prev = Ht_row[c]
    return 0

